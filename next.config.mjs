/** @type {import('next').NextConfig} */

// The grading engine is OpenCV.js compiled with Emscripten. Its embind runtime
// builds functions at runtime (new Function), so 'unsafe-eval' is required —
// 'wasm-unsafe-eval' alone does not cover it and would break grading outright.
// Fonts are self-hosted by next/font and the app makes no network requests of
// its own, so connect-src stays locked to 'self'. Uploaded photos and generated
// debug overlays are blob:/data: URLs.
const csp = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline' 'unsafe-eval' https://cdn.jsdelivr.net",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' blob: data:",
  "font-src 'self' data:",
  "connect-src 'self' https://cdn.jsdelivr.net",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ');

const nextConfig = {
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          { key: 'Content-Security-Policy', value: csp },
          { key: 'X-Content-Type-Options', value: 'nosniff' },
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
          { key: 'X-Frame-Options', value: 'DENY' },
          // Exam photos never leave the browser; deny the hardware APIs outright.
          { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=(), interest-cohort=()' },
        ],
      },
    ];
  },
};

export default nextConfig;
